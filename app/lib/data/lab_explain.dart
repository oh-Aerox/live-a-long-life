      SettingsRepository settings, String key) async {
    final all = await settings.get(generatedKey);
    if (all is! Map || all[key] is! Map) return null;
    final e = all[key] as Map;
    return GeneratedLabExplanation(
        LabExplanation.fromJson(e['explanation']), '${e['date'] ?? ''}');
  }

