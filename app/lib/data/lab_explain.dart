/// 检验指标说明（D-50）：指标趋势详情里"这一项是什么"——含义、偏高 / 偏低
/// （定性项目是阳性）可能意味着什么、常和哪些指标一起看。是通用的科普
/// 说明，不针对某一次结果，不做诊断。
///
/// 来源两种：内置指标目录里的项目由 [builtIn] 提供（代码常量，随应用发布，
/// 手机和 Mac 都能看）；目录外的项目可以在详情页让模型生成一次，存在本机
/// 设置 [generatedKey] 里（不同步，各设备各自生成；随导出与备份）。身高体重这类常识项目、
/// 过敏原不写。
class LabExplanation {
  const LabExplanation(
    this.meaning, {
    this.high,
    this.low,
    this.related,
    this.highLabel = '偏高',
  });

  /// 这一项测的是什么、反映什么。
  final String meaning;

  /// 偏高（定性项目为阳性）可能意味着什么；没什么可说的为 null。
  final String? high;

  /// 偏低可能意味着什么；没什么可说的为 null。
  final String? low;

  /// 常和哪些指标一起看、为什么。
  final String? related;

  /// [high] 的标题："偏高"，定性项目为"阳性"。
  final String highLabel;

  Map<String, Object?> toJson() => {
        'meaning': meaning,
        'high': high,
        'low': low,
        'related': related,
        'high_label': highLabel,
      };

  static LabExplanation? fromJson(Object? j) {
    if (j is! Map || j['meaning'] is! String) return null;
    String? s(String k) =>
        j[k] is String && (j[k] as String).trim().isNotEmpty
            ? (j[k] as String).trim()
            : null;
    return LabExplanation(
      (j['meaning'] as String).trim(),
      high: s('high'),
      low: s('low'),
      related: s('related'),
      highLabel: s('high_label') == '阳性' ? '阳性' : '偏高',
    );
  }
}

/// 模型生成的说明（本机设置里的一条）。
class GeneratedLabExplanation {
  const GeneratedLabExplanation(this.explanation, this.date);

  /// 模型认为不需要说明（常识项目、过敏原）时为 null，同样记下，不再问。
  final LabExplanation? explanation;
  final String date;
}

