    final all = await settings.get(generatedKey);
    final next = {
      if (all is Map) ...all.cast<String, Object?>(),
      key: {'explanation': explanation?.toJson(), 'date': date},
    };
    await settings.set(generatedKey, jsonDecode(jsonEncode(next)));
  }

