class LabCatalogEntry {
  const LabCatalogEntry(this.name, this.group, this.aliases);

  /// 标准中文名，即趋势里这一项的键与标题。
  final String name;

  /// 指标趋势里的分组。
  final String group;

  /// 常见别名与英文缩写（清洗后的写法）。
  final List<String> aliases;

  /// 标本：尿 / 便；血液和其他为 null。
  String? get specimen => name.startsWith('便')
      ? '便'
      : RegExp(r'^尿(?!酸|素)').hasMatch(name)
          ? '尿'
          : null;
}
