/// 英文缩写、所属分组。名称以卫生行业标准（WS/T 404 临床常用生化检验项目
/// 参考区间、WS/T 405 血细胞分析参考区间等）和《全国临床检验操作规程》的
/// 叫法为准。
///
/// 用法：[SameItem.ruleKey] 先按本地规则清洗项目名（去缩写括号、方法、
/// 互认标记，尿便项目加标本前缀），再用 [canonical] 查目录换成标准名；
/// 查不到的保留清洗后的名字。提取时把目录发给模型对号入座（prompts §3）。
///
/// 收录原则：只收同一指标、同一标本的叫法；口径不同的（尿素与尿素氮、
/// 游离与总 PSA、肌酸激酶与同工酶）各自成项。别名写成清洗后的样子
/// （不带括号缩写、不分大小写、全角半角括号等同）。
class LabCatalog {
  const LabCatalog._();

  /// 标准名 → 条目。
  static final Map<String, LabCatalogEntry> byName = {
    for (final e in entries) e.name: e,
  };

  static final Map<String, String> _index = () {
    final m = <String, String>{};
    for (final e in entries) {
      for (final a in [e.name, ...e.aliases]) {
        assert(m[_norm(a)] == null || m[_norm(a)] == e.name, '别名重复：$a');
        m[_norm(a)] = e.name;
      }
    }
    return m;
  }();

  static String _norm(String s) => s
      .toLowerCase()
      .replaceAll('(', '（')
      .replaceAll(')', '）')
      .replaceAll('－', '-')
      .replaceAll(RegExp(r'\s'), '');

  /// 清洗后的键在目录里的标准名；不在目录里的原样返回。
  static String canonical(String key) => _index[_norm(key)] ?? key;

  /// 键是否是目录里的项目（标准名或别名）。
  static bool contains(String key) => _index.containsKey(_norm(key));

  /// 目录给的分组；不在目录里的为 null（再按项目规则、报告大项认）。
  static String? groupOf(String key) => byName[canonical(key)]?.group;

  /// 发给模型的目录：每行"分组：标准名（别名、缩写）…"。
  static String promptText() {
    final byGroup = <String, List<LabCatalogEntry>>{};
    for (final e in entries) {
      (byGroup[e.group] ??= []).add(e);
    }
    return [
      for (final MapEntry(:key, :value) in byGroup.entries)
        '$key：${value.map((e) => e.aliases.isEmpty ? e.name : '${e.name}（${e.aliases.join('、')}）').join('；')}',
    ].join('\n');
  }

